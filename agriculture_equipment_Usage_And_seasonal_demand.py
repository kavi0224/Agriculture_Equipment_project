df.to_csv("agriculture_equipment_dataset.csv", index=False)
equipment_usage.to_csv("equipment_usage_results.csv")
seasonal.to_csv("seasonal_demand_results.csv")
monthly.to_csv("monthly_demand_results.csv", index=False)
state_usage.to_csv("state_wise_usage_results.csv")
pivot.to_csv("equipment_season_heatmap_data.csv")

