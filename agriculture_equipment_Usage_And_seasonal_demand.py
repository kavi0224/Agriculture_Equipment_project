# ==========================================================

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from IPython.display import display

# Graph settings
sns.set_theme(style="whitegrid")
plt.rcParams["figure.figsize"] = (10, 6)
plt.rcParams["font.size"] = 11

print("=" * 65)
print("AGRICULTURE EQUIPMENT USAGE AND SEASONAL DEMAND")
print("=" * 65)

# 1. CREATE SAMPLE DATASET
np.random.seed(42)

states = [
    "Tamil Nadu", "Punjab", "Haryana", "Karnataka",
    "Maharashtra", "Uttar Pradesh", "Andhra Pradesh",
    "Telangana", "Gujarat", "Kerala"
]

equipment = [
    "Tractor", "Power Tiller", "Seed Drill",
    "Combine Harvester", "Pump Set", "Sprayer",
    "Thresher", "Rotavator", "Cultivator", "Plough"
]

months = list(range(1, 13))

month_names = {
    1: "Jan", 2: "Feb", 3: "Mar", 4: "Apr",
    5: "May", 6: "Jun", 7: "Jul", 8: "Aug",
    9: "Sep", 10: "Oct", 11: "Nov", 12: "Dec"
}

season_map = {
    1: "Winter", 2: "Winter",
    3: "Summer", 4: "Summer", 5: "Summer",
    6: "Kharif", 7: "Kharif", 8: "Kharif", 9: "Kharif",
    10: "Rabi", 11: "Rabi", 12: "Rabi"
}

season_factor = {
    "Winter": 0.85,
    "Summer": 0.95,
    "Kharif": 1.40,
    "Rabi": 1.15
}

equipment_factor = {
    "Tractor": 1.40,
    "Power Tiller": 0.85,
    "Seed Drill": 1.00,
    "Combine Harvester": 1.10,
    "Pump Set": 1.20,
    "Sprayer": 1.15,
    "Thresher": 0.90,
    "Rotavator": 1.05,
    "Cultivator": 0.95,
    "Plough": 0.90
}

records = []

for state in states:
    for month in months:
        season = season_map[month]

        for item in equipment:
            base = 100 * season_factor[season]
            base *= equipment_factor[item]

            usage = int(
                base
                * np.random.uniform(0.70, 1.30)
                * np.random.uniform(0.85, 1.15)
            )

            records.append({
                "State": state,
                "Month": month,
                "Month_Name": month_names[month],
                "Season": season,
                "Equipment": item,
                "Usage_Count": max(1, usage)
            })

df = pd.DataFrame(records)

print("\nDATASET CREATED")
print("Total records:", len(df))
print("States:", df["State"].nunique())
print("Equipment types:", df["Equipment"].nunique())

display(df.head(10))

# ==========================================================
# GRAPH 1: EQUIPMENT-WISE USAGE
# ==========================================================

equipment_usage = (
    df.groupby("Equipment")["Usage_Count"]
    .sum()
    .sort_values(ascending=False)
)

plt.figure(figsize=(12, 6))
equipment_usage.plot(kind="bar", color="steelblue", edgecolor="black")
plt.title("Graph 1: Agricultural Equipment Usage")
plt.xlabel("Equipment Type")
plt.ylabel("Total Usage Count")
plt.xticks(rotation=40, ha="right")
plt.tight_layout()
plt.show()

# ==========================================================
# GRAPH 2: SEASONAL DEMAND
# ==========================================================

season_order = ["Winter", "Summer", "Kharif", "Rabi"]

seasonal = (
    df.groupby("Season")["Usage_Count"]
    .sum()
    .reindex(season_order)
)

plt.figure(figsize=(9, 5))
seasonal.plot(kind="bar", color="seagreen", edgecolor="black")
plt.title("Graph 2: Seasonal Agricultural Equipment Demand")
plt.xlabel("Season")
plt.ylabel("Total Demand Count")
plt.xticks(rotation=0)
plt.tight_layout()
plt.show()

# ==========================================================
# GRAPH 3: MONTH-WISE DEMAND
# ==========================================================

monthly = (
    df.groupby(["Month", "Month_Name"])["Usage_Count"]
    .sum()
    .reset_index()
    .sort_values("Month")
)

plt.figure(figsize=(12, 5))
plt.plot(
    monthly["Month_Name"],
    monthly["Usage_Count"],
    marker="o",
    linewidth=2,
    markersize=7
)
plt.title("Graph 3: Monthly Equipment Demand")
plt.xlabel("Month")
plt.ylabel("Total Demand Count")
plt.grid(True)
plt.tight_layout()
plt.show()

# ==========================================================
# GRAPH 4: STATE-WISE EQUIPMENT USAGE
# ==========================================================

state_usage = (
    df.groupby("State")["Usage_Count"]
    .sum()
    .sort_values(ascending=False)
)

plt.figure(figsize=(12, 6))
state_usage.plot(kind="bar", color="orange", edgecolor="black")
plt.title("Graph 4: State-wise Agricultural Equipment Usage")
plt.xlabel("State")
plt.ylabel("Total Usage Count")
plt.xticks(rotation=40, ha="right")
plt.tight_layout()
plt.show()

# ==========================================================
# GRAPH 5: EQUIPMENT VS SEASON HEATMAP
# ==========================================================

pivot = df.pivot_table(
    index="Equipment",
    columns="Season",
    values="Usage_Count",
    aggfunc="sum"
)

pivot = pivot.reindex(columns=season_order)

plt.figure(figsize=(11, 7))
sns.heatmap(
    pivot,
    annot=True,
    fmt=".0f",
    cmap="YlGnBu",
    linewidths=0.5
)
plt.title("Graph 5: Equipment Usage Across Seasons")
plt.xlabel("Season")
plt.ylabel("Equipment Type")
plt.tight_layout()
plt.show()

# ==========================================================
# GRAPH 6: EQUIPMENT USAGE PERCENTAGE
# ==========================================================

plt.figure(figsize=(10, 8))
plt.pie(
    equipment_usage.values,
    labels=equipment_usage.index,
    autopct="%1.1f%%",
    startangle=90
)
plt.title("Graph 6: Equipment Usage Percentage")
plt.tight_layout()
plt.show()

# ==========================================================
# GRAPH 7: EQUIPMENT-WISE SEASONAL COMPARISON
# ==========================================================

comparison = df.pivot_table(
    index="Season",
    columns="Equipment",
    values="Usage_Count",
    aggfunc="sum"
).reindex(season_order)

comparison.plot(
    kind="bar",
    figsize=(15, 7),
    colormap="tab10"
)
plt.title("Graph 7: Equipment Demand Comparison by Season")
plt.xlabel("Season")
plt.ylabel("Total Usage Count")
plt.xticks(rotation=0)
plt.legend(
    title="Equipment",
    bbox_to_anchor=(1.02, 1),
    loc="upper left"
)
plt.tight_layout()
plt.show()

# ==========================================================
# GRAPH 8: MONTHLY DEMAND BY SEASON
# ==========================================================

plt.figure(figsize=(12, 6))
sns.lineplot(
    data=df.groupby(
        ["Month", "Month_Name", "Season"], as_index=False
    )["Usage_Count"].sum(),
    x="Month",
    y="Usage_Count",
    hue="Season",
    marker="o"
)
plt.title("Graph 8: Monthly Demand Trends by Season")
plt.xlabel("Month Number")
plt.ylabel("Total Usage Count")
plt.xticks(range(1, 13))
plt.tight_layout()
plt.show()

# ==========================================================
# ANALYSIS RESULTS
# ==========================================================

print("\n" + "=" * 60)
print("PROJECT ANALYSIS RESULTS")
print("=" * 60)

print("\n1. TOP 10 EQUIPMENT USAGE")
display(equipment_usage.rename("Total_Usage").to_frame())

print("\n2. SEASONAL DEMAND")
display(seasonal.rename("Total_Demand").to_frame())

print("\n3. MONTHLY DEMAND")
display(monthly)

print("\n4. STATE-WISE USAGE")
display(state_usage.rename("Total_Usage").to_frame())

print("\n5. HIGHEST USAGE EQUIPMENT:")
print(equipment_usage.idxmax())

print("\n6. HIGHEST DEMAND SEASON:")
print(seasonal.idxmax())

print("\n7. HIGHEST DEMAND MONTH:")
print(monthly.loc[monthly["Usage_Count"].idxmax(), "Month_Name"])

